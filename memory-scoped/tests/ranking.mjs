import assert from 'node:assert/strict';
import {rankMemory,retention,timestamp,tokenize} from '../lib/memory-rank.mjs';
const now=1800000000000,day=86400000;
const row=(id,text,age,layer='records')=>({id,text,at:now-age*day,layer,source:'native_record'});
assert(tokenize('之前提到的咖啡 DeepSeek').includes('咖啡'));
assert.equal(timestamp('2026-10-31T00:00:00Z'),1793404800000);
assert.equal(timestamp(1800000000),now);
const items=[row('old','之前选了蓝色咖啡杯',100),row('new','今天选了白色咖啡杯',1)];
assert.equal(rankMemory(items,'咖啡杯',{now}).items[0].id,'new');
assert(rankMemory(items,'蓝色咖啡杯',{now}).items.some(x=>x.id==='old'));
assert.equal(retention(row('fact','重要事实',10000,'important'),now),1);
assert(retention(items[0],now)>.35);
assert.equal(rankMemory(items,'望远镜',{now}).items.length,0);
const anchored=[{...row('question','咖啡还要不要糖',0),recordIndex:0},{...row('answer','不用啦，清爽一点',0),recordIndex:1}];
const result=rankMemory(anchored,'咖啡',{now});assert.equal(result.items.length,2);assert.equal(result.items[1].match,'adjacent_context');assert.equal(result.items[1].linkedTo,'question');
anchored[1].at-=180000;assert.equal(rankMemory(anchored,'咖啡',{now}).items.length,1);
const long=Array.from({length:6},(_,i)=>row(String(i),'填充'.repeat(700)+'咖啡'+String(i)+'内容'.repeat(700),i));
const bounded=rankMemory(long,'咖啡',{now,limit:6});assert(bounded.items.reduce((n,x)=>n+x.text.length,0)<=4000);assert(bounded.items.every(x=>x.text.includes('咖啡')));
const before=JSON.stringify(items);const one=rankMemory(items,'咖啡',{now}),two=rankMemory(items,'咖啡',{now});assert.deepEqual(one,two);assert.equal(JSON.stringify(items),before);
assert.equal(rankMemory([row('a','咖啡记录',20),row('b','咖啡记录',1)],'咖啡',{now}).items.length,1);
console.log('PASS ranking: Chinese/English keywords, relevance, recency decay floor, important retention, one-hop context, output limits, excerpts, deterministic no-reinforcement, dedupe');
